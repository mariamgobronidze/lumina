mathForm.addEventListener("submit", (event) => {
  event.preventDefault();
  if (currentMathSolved) return;
  const value = mathAnswer.value.trim();
  if (!/^-?\d+$/.test(value)) {
    mathFeedbackKey = "mathAnswerInvalid";
    renderMath();
    return;
  }
  if (Number(value) === currentMathProblem.answer) {
    currentMathSolved = true;
    mathFeedbackKey = "mathCorrect";
    stars += 1;
    try {
      localStorage.setItem("lumina_stars", String(stars));
    } catch {
      mathFeedbackKey = "mathStarsNotSaved";
    }
    renderMath();
  } else {
    mathFeedbackKey = "mathIncorrect";
    renderMath();
  }
});

