function readStoredData() {
  try {
    const storedStars = Number(localStorage.getItem("lumina_stars"));
    stars = Number.isSafeInteger(storedStars) && storedStars >= 0 ? storedStars : 0;
    const profileText = localStorage.getItem("lumina_saved_profile");
    if (profileText) {
      const profile = JSON.parse(profileText);
      const firstName = typeof profile.firstName === "string" ? profile.firstName.trim() : "";
      const lastName = typeof profile.lastName === "string" ? profile.lastName.trim() : "";
      if (
        firstName.length > 0 &&
        lastName.length > 0 &&
        typeof profile.email === "string" &&
        typeof profile.phone === "string" &&
        isPasscode(profile.passcode)
      ) {
        savedProfile = { ...profile, firstName, lastName };
      } else {
        startupError = "profileReadError";
      }
    }
  } catch {
    startupError = "profileReadError";
  }

  try {
    const pendingText = sessionStorage.getItem("lumina_pending_registration");
    if (pendingText) {
      const pending = JSON.parse(pendingText);
      if (
        typeof pending.firstName === "string" &&
        typeof pending.lastName === "string" &&
        typeof pending.email === "string" &&
        typeof pending.phone === "string" &&
        /^\d{4}$/.test(pending.emailCode) &&
        pending.emailSent === true
      ) {
        pendingRegistration = pending;
      } else {
        sessionStorage.removeItem("lumina_pending_registration");
      }
    }
  } catch {
    startupError = "storageError";
  }
}

function speakText(text, language = currentLanguage) {
  if (!window.speechSynthesis || typeof window.SpeechSynthesisUtterance !== "function") {
    return false;
  }
  window.speechSynthesis.cancel();
  const utterance = new window.SpeechSynthesisUtterance(text);
  utterance.lang = { ka: "ka-GE", en: "en-US", ru: "ru-RU" }[language];
  window.speechSynthesis.speak(utterance);
  return true;
}

