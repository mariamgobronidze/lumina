function isLocalDevelopmentHost() {
  return ["localhost", "127.0.0.1", "::1"].includes(window.location.hostname);
}

function isPasscode(value) {
  return /^[\p{L}\p{N}]{6}$/u.test(value);
}

function showScreen(screenId) {
  currentScreen = screenId;
  signupScreen.hidden = screenId !== "signup-screen";
  verificationScreen.hidden = screenId !== "verification-screen";
  loginScreen.hidden = screenId !== "login-screen";
  homeScreen.hidden = screenId !== "home-screen";
  showLoginButton.hidden = screenId !== "signup-screen";
  screenStack.classList.toggle("home-mode", screenId === "home-screen");
  clearErrors();
  const pageKey = {
    "signup-screen": "pageRegistration",
    "verification-screen": "pageVerification",
    "login-screen": "pageLogin",
    "home-screen": "pageHome"
  }[screenId];
  document.title = `Lumina — ${translations[currentLanguage][pageKey]}`;
  if (screenId === "home-screen") renderHome();
}

function clearErrors() {
  [signupError, verificationError, loginError].forEach((error) => {
    error.hidden = true;
    error.textContent = "";
    delete error.dataset.translationKey;
    delete error.dataset.errorDetails;
  });
}

function showError(element, key, details = "") {
  element.dataset.translationKey = key;
  element.dataset.errorDetails = details;
  element.textContent = details
    ? `${translations[currentLanguage][key]} ${details}`
    : translations[currentLanguage][key];
  element.hidden = false;
}

