signupForm.addEventListener("submit", async (event) => {
  event.preventDefault();
  clearErrors();

  const formData = new FormData(signupForm);
  const user = {
    firstName: String(formData.get("firstName")).trim(),
    lastName: String(formData.get("lastName")).trim(),
    email: String(formData.get("email")).trim(),
    phone: String(formData.get("phone")).trim()
  };
  if (Object.values(user).some((value) => value.length === 0)) {
    showError(signupError, "signupRequired");
    return;
  }
  if (!document.querySelector("#email").checkValidity()) {
    showError(signupError, "signupEmailInvalid");
    return;
  }

  if (isSending) return;
  try {
    sessionStorage.removeItem("lumina_pending_registration");
  } catch {
    showError(signupError, "storageError");
    return;
  }
  if (typeof window.fetch !== "function") {
    showError(signupError, isLocalDevelopmentHost() ? "localApiUnavailable" : "emailServiceUnavailable");
    return;
  }

  const generatedMailCode = String(Math.floor(1000 + Math.random() * 9000));
  const registration = {
    ...user,
    emailCode: generatedMailCode,
    emailSent: true
  };
  setSignupSending(true);
  try {
    const response = await fetch("/api/send-code", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        firstName: user.firstName,
        lastName: user.lastName,
        email: user.email,
        code: generatedMailCode
      })
    });
    const result = await response.json().catch(() => ({}));
    if (!response.ok || result.success !== true) {
      if (isLocalDevelopmentHost() && [404, 405, 501].includes(response.status)) {
        showError(signupError, "localApiUnavailable");
        return;
      }
      const reason = typeof result.details === "string" && result.details
        ? result.details
        : typeof result.error === "string" && result.error
          ? result.error
          : `HTTP ${response.status}`;
      showError(signupError, "emailSendError", reason);
      return;
    }
  } catch (err) {
    if (isLocalDevelopmentHost()) {
      showError(signupError, "localApiUnavailable");
      return;
    }
    const reason = err?.message || err;
    const details = typeof reason === "string" ? reason : String(reason);
    showError(signupError, "emailSendError", details);
    return;
  } finally {
    setSignupSending(false);
  }

  pendingRegistration = registration;
  let sessionStorageFailed = false;
  try {
    sessionStorage.setItem("lumina_pending_registration", JSON.stringify(pendingRegistration));
  } catch {
    sessionStorageFailed = true;
  }
  verificationForm.reset();
  showScreen("verification-screen");
  if (sessionStorageFailed) showError(verificationError, "verificationSessionWarning");
});

verificationForm.addEventListener("submit", (event) => {
  event.preventDefault();
  clearErrors();
  if (!pendingRegistration) {
    showError(verificationError, "noPendingRegistration");
    return;
  }

  const emailCode = verificationForm.elements.namedItem("emailCode").value.trim();
  const passcode = verificationForm.elements.namedItem("passcode").value;
  if (!/^\d{4}$/.test(emailCode)) {
    showError(verificationError, "emailCodeInvalid");
    return;
  }
  if (emailCode !== pendingRegistration.emailCode) {
    showError(verificationError, "emailCodeMismatch");
    return;
  }
  if (!isPasscode(passcode)) {
    showError(verificationError, "passcodeInvalid");
    return;
  }

  const profile = {
    firstName: pendingRegistration.firstName,
    lastName: pendingRegistration.lastName,
    email: pendingRegistration.email,
    phone: pendingRegistration.phone,
    passcode
  };
  try {
    localStorage.setItem("lumina_saved_profile", JSON.stringify(profile));
    localStorage.setItem("lumina_stars", "0");
    localStorage.removeItem("luminaUser");
    localStorage.removeItem("luminaVerification");
    sessionStorage.removeItem("lumina_pending_registration");
  } catch {
    showError(verificationError, "storageError");
    return;
  }

  savedProfile = profile;
  pendingRegistration = null;
  stars = 0;
  currentMathProblem = null;
  mathFeedbackKey = "";
  profileName.textContent = `${profile.firstName} ${profile.lastName}`;
  showScreen("home-screen");
});

