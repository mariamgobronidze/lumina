function translatePage(language) {
  currentLanguage = language;
  const messages = translations[language];
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (key === "themeNight" || key === "themeDay") {
      element.textContent = document.body.dataset.theme === "night" ? messages.themeDay : messages.themeNight;
    } else {
      element.textContent = messages[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = messages[element.dataset.i18nPlaceholder];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", messages[element.dataset.i18nAria]);
  });

  languageSelect.setAttribute("aria-label", messages.languageLabel);
  [signupError, verificationError, loginError].forEach((error) => {
    if (!error.hidden && error.dataset.translationKey) {
      error.textContent = error.dataset.errorDetails
        ? `${messages[error.dataset.translationKey]} ${error.dataset.errorDetails}`
        : messages[error.dataset.translationKey];
    }
  });
  if (isSending) signupButtonLabel.textContent = messages.sendingButton;
  if (savedProfile) {
    profileName.textContent = `${savedProfile.firstName} ${savedProfile.lastName}`;
  }
  document.title = `Lumina — ${messages[{
    "signup-screen": "pageRegistration",
    "verification-screen": "pageVerification",
    "login-screen": "pageLogin",
    "home-screen": "pageHome"
  }[currentScreen]]}`;
  if (currentScreen === "home-screen") renderLearningContent();
}

