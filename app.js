function renderMath() {
  if (!currentMathProblem) return;
  mathQuestion.textContent = `${currentMathProblem.first} ${currentMathProblem.operator} ${currentMathProblem.second} = ?`;
  starsCounter.textContent = translations[currentLanguage].starsCounter.replace("{count}", stars);
  mathFeedback.textContent = mathFeedbackKey ? translations[currentLanguage][mathFeedbackKey] : "";
  nextProblemButton.hidden = !currentMathSolved;
}

function makeMathProblem() {
  let first = Math.floor(Math.random() * 25) + 1;
  let second = Math.floor(Math.random() * 25) + 1;
  const operator = Math.random() < 0.5 ? "+" : "−";
  if (operator === "−" && second > first) {
    [first, second] = [second, first];
  }
  currentMathProblem = {
    first,
    second,
    operator,
    answer: operator === "+" ? first + second : first - second
  };
  currentMathSolved = false;
  mathFeedbackKey = "";
  mathAnswer.value = "";
  renderMath();
}

